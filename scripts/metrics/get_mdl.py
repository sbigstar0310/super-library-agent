ScoreFn = Callable[[MDLMetric, Entry, TaskConfig, LibNllCache, bool], Awaitable[AppMDLResult]]


async def _score_entry_dep_aware(
    metric: MDLMetric, entry: Entry, task: TaskConfig,
    cache: LibNllCache, strip_comments: bool,
) -> AppMDLResult:
    precomp = await cache.get(entry.lib_dir)
    return await metric.ascore(
        entry.app_dir, entry.lib_dir,
        task=task, precomputed_lib=precomp,
        strip_comments=strip_comments,
    )


async def _score_entry_concat(
    metric: MDLMetric, entry: Entry, task: TaskConfig,
    cache: LibNllCache, strip_comments: bool,
) -> AppMDLResult:
    precomp = await cache.get(entry.lib_dir)
    return await score_concat(
        metric, entry.app_dir, entry.lib_dir,
        task=task, strip_comments=strip_comments, precomputed_lib=precomp,
    )


METHOD_SCORERS: dict[str, ScoreFn] = {
    "dep_aware": _score_entry_dep_aware,
    "concat":    _score_entry_concat,
}


async def _run_shared_concat(
    metric: MDLMetric,
    entries: list[Entry],
    task: TaskConfig,
    strip_comments: bool,
    verbose: bool,
) -> list[tuple[Entry, dict]]:
    """Group entries by lib_dir, run one ``score_shared_concat`` per group.

    Lib NLL is measured once per unique lib_dir and re-attached identically to
    every app record in the group. ``_summarize_shared`` counts it once.
    """
    groups: dict[str, list[Entry]] = {}
    order: list[str] = []
    for e in entries:
        key = os.path.abspath(e.lib_dir) if e.lib_dir else "__no_lib__"
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append(e)

    out: list[tuple[Entry, dict]] = []
    lib_cache: dict[str, tuple[float, int, str]] = {}
    for key in order:
        group = groups[key]
        lib_dir = group[0].lib_dir
        app_dirs = [(e.label, e.app_dir) for e in group]
        precomp = lib_cache.get(key)
        print(f"Getting shared-concat MDL for {len(group)} app(s) sharing lib={lib_dir or '(none)'}")
        suite = await score_shared_concat(
            metric, app_dirs, lib_dir,
            task=task, strip_comments=strip_comments,
            precomputed_lib=precomp,
        )
        lib_cache[key] = (suite.library_nll, suite.library_tokens, suite.lib_text_hash)
        print(f"  lib_nll={suite.library_nll:.1f} ({suite.library_tokens} tokens) "
              f"hash={suite.lib_text_hash[:8]}")
        for entry, result in zip(group, suite.app_results):
            out.append((entry, result.as_dict()))
            if verbose:
                _print_verbose(result, "shared_concat")
    return out


def _print_verbose(result: AppMDLResult, method: str) -> None:
    has_deps = method == "dep_aware"
    header = f"  {'File':<35s} {'NLL':>8s} {'Tokens':>7s} {'NLL/tok':>8s}"
    if has_deps:
        header += "  Deps"
    print(header)
    for fd in result.file_details:
        line = f"  {fd.rel_path:<35s} {fd.nll:>8.1f} {fd.tokens:>7d} {fd.nll_per_token:>8.3f}"
        if has_deps:
            deps_str = ", ".join(os.path.basename(p) for p in fd.dep_paths) if fd.dep_paths else "(none)"
            line += f"  {deps_str}"
        print(line)
    npt = result.app_nll / result.app_tokens if result.app_tokens > 0 else float("nan")
    print(f"  {'TOTAL':<35s} {result.app_nll:>8.1f} {result.app_tokens:>7d} {npt:>8.3f}")
    print()


# ----------------------------------------------------------------------
# Aggregation + JSON output
# ----------------------------------------------------------------------

def _summarize(results: list[dict]) -> dict:
    if not results:
        return {"sum_app_nll": 0.0, "avg_library_nll": 0.0, "mdl_nll": 0.0, "total_apps": 0}
    total_app_nll = sum(float(r.get("app_nll", 0.0)) for r in results)
    avg_lib_nll = sum(float(r.get("library_nll", 0.0)) for r in results) / len(results)
    return {
        "sum_app_nll": round(total_app_nll, 4),
        "avg_library_nll": round(avg_lib_nll, 4),
        "mdl_nll": round(total_app_nll + avg_lib_nll, 4),
        "total_apps": len(results),
    }


def _summarize_shared(results: list[dict]) -> dict:
    """Lib counted once (not averaged). All records carry identical library_nll
    within a single suite — pick the first one. For per-task files (one record
    each), this collapses to the same value."""
    if not results:
        return {
            "library_nll": 0.0, "library_tokens": 0,
            "sum_app_nll": 0.0, "sum_app_tokens": 0,
            "mdl_nll": 0.0, "total_tokens": 0,
            "nll_per_token": 0.0, "total_apps": 0,
        }
    lib_nll = float(results[0].get("library_nll", 0.0))
    lib_tokens = int(results[0].get("library_tokens", 0))
    sum_app_nll = sum(float(r.get("app_nll", 0.0)) for r in results)
    sum_app_tokens = sum(int(r.get("app_tokens", 0)) for r in results)
    total_nll = lib_nll + sum_app_nll
    total_tokens = lib_tokens + sum_app_tokens
    return {
        "library_nll": round(lib_nll, 4),
        "library_tokens": lib_tokens,
        "sum_app_nll": round(sum_app_nll, 4),
        "sum_app_tokens": sum_app_tokens,
        "mdl_nll": round(total_nll, 4),
        "total_tokens": total_tokens,
        "nll_per_token": round(total_nll / total_tokens, 4) if total_tokens else 0.0,
        "total_apps": len(results),
    }


FNAME_BY_METHOD = {
    "dep_aware":     ("mdl_results.json",        "mdl_summary.json"),
    "concat":        ("mdl_results_old.json",    "mdl_summary_old.json"),
    "shared_concat": ("mdl_results_shared.json", "mdl_summary_shared.json"),
}


def _summarize_for_method(method: str, results: list[dict]) -> dict:
    if method == "shared_concat":
        return _summarize_shared(results)
    return _summarize(results)


def _write_outputs(
    *, task: str, method: str,
    records: list[tuple[Entry, dict]],
    eval_root: str | None, webgen_legacy_save_dir: str | None,
) -> None:
    fname, summary_fname = FNAME_BY_METHOD[method]

    # Per-entry files (paperbench + webgen-unified)
    per_entry_layout = (
        task == "paperbench"
        or (task == "webgen" and eval_root is not None)
    )
    if per_entry_layout:
        for entry, rec in records:
            sd = entry.save_dir
            if sd is None:
                continue
            os.makedirs(sd, exist_ok=True)
            payload = {"apps": [rec], "summary": _summarize_for_method(method, [rec])}
            out_path = os.path.join(sd, fname)
            with open(out_path, "w", encoding="utf-8") as f:
                json.dump(payload, f, indent=2, ensure_ascii=False)
            print(f"Saved to: {out_path}")
        if eval_root and records:
            os.makedirs(eval_root, exist_ok=True)
            agg = {
                "apps": [rec for _, rec in records],
                "summary": _summarize_for_method(method, [rec for _, rec in records]),
            }
            agg_path = os.path.join(eval_root, summary_fname)
            with open(agg_path, "w", encoding="utf-8") as f:
                json.dump(agg, f, indent=2, ensure_ascii=False)
            print(f"Aggregated to: {agg_path}")
        return

    # Webgen-legacy: one combined file
    payload = {
        "apps": [rec for _, rec in records],
        "summary": _summarize_for_method(method, [rec for _, rec in records]),
    }
    if webgen_legacy_save_dir:
        os.makedirs(webgen_legacy_save_dir, exist_ok=True)
        out_path = os.path.join(webgen_legacy_save_dir, fname)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2, ensure_ascii=False)
        print(f"Saved to: {out_path}")
    else:
        print(json.dumps(payload, ensure_ascii=False, indent=2))


