# Entry point
# ----------------------------------------------------------------------

async def run(args: argparse.Namespace) -> None:
    task = load_task_config(args.task)
    resolved = resolve(args, task)

    for line in resolved.header_lines:
        print(line)
    if not resolved.entries:
        print("[info] no entries to score.")
        return

    metric = MDLMetric(
        model=args.model,
        base_url=args.openai_base_url,
        api_key=args.openai_api_key,
        joiner=args.joiner,
        max_concurrency=args.max_concurrency,
    )
    if args.method == "shared_concat":
        records = await _run_shared_concat(
            metric, resolved.entries, task, args.strip_comments, args.verbose,
        )
    else:
        cache = LibNllCache(metric, task, strip_comments=args.strip_comments)
        score_one = METHOD_SCORERS[args.method]
        records: list[tuple[Entry, dict]] = []
        for entry in resolved.entries:
            label_method = "dep-aware" if args.method == "dep_aware" else "concat"
            print(f"Getting {label_method} MDL for {entry.label}")
            result = await score_one(metric, entry, task, cache, args.strip_comments)
            records.append((entry, result.as_dict()))
            if args.verbose:
                _print_verbose(result, args.method)

    _write_outputs(
        task=args.task, method=args.method, records=records,
        eval_root=resolved.eval_root, webgen_legacy_save_dir=args.save_dir,
    )


def main() -> None:
    load_dotenv(os.path.join(PROJECT_DIR, ".env"))

    p = argparse.ArgumentParser(description="MDL/NLL metric (dep-aware or concat).")
    p.add_argument("--task", default="webgen",
                   choices=["webgen", "paperbench"])
    p.add_argument("--bench", default=None,
                   help="Backup root override under backups/ (default: same "
                        "as --task; e.g. webgen-maint for maintenance runs).")

    # Webgen-legacy explicit dirs
    p.add_argument("--app_root_dir", default=None,
                   help="[webgen-legacy] App-root dir (subdir per app).")
    p.add_argument("--lib_dir", default=None,
                   help="Override library dir. For paperbench/webgen-unified, "
                        "this overrides the auto-detected per-task lib.")
    p.add_argument("--app-ids", default=None, dest="app_ids",
                   help="[webgen-legacy] Comma-separated app IDs.")

    # Backup-tag based modes
    p.add_argument("--backup-tag", default=None, dest="backup_tag")
    p.add_argument("--paper-ids", default=None, dest="paper_ids",
                   help="[paperbench] Comma-separated paper IDs.")
    p.add_argument("--task-ids", default=None, dest="task_ids",
                   help="[paperbench/webgen-unified] Comma-separated task IDs.")
    p.add_argument("--round", default=None, type=int, dest="round",
                   help="[unified] round_<N>. Default: latest having --phase on disk.")
    p.add_argument("--phase", default=None,
                   help="[unified] baseline|coding|apply|extract.")

    # Scoring
    p.add_argument("--method", default="dep_aware",
                   choices=["dep_aware", "concat", "shared_concat"])
    p.add_argument("--model", default="Qwen/Qwen2.5-7B")
    p.add_argument("--joiner", default="\n")
    p.add_argument("--max_concurrency", type=int, default=1)
    p.add_argument("--openai_base_url",
                   default=os.environ.get("MDL_BASE_URL", "http://127.0.0.1:8000/v1"),
                   help="vLLM endpoint; defaults to the server deploy_vllm.sh starts locally. "
                        "Also settable via MDL_BASE_URL.")
    p.add_argument("--openai_api_key", default="EMPTY")

    p.add_argument("--save_dir", default=None,
                   help="[webgen-legacy] Output dir; ignored for backup-tag modes.")
    p.add_argument("--verbose", action="store_true")
    p.add_argument("--no-strip-comments", action="store_true",
                   help="Disable comment stripping (default: stripped).")

    args = p.parse_args()
    if isinstance(args.lib_dir, str) and args.lib_dir.strip().lower() in {"none", "null", ""}:
        args.lib_dir = None
    args.strip_comments = not args.no_strip_comments

    asyncio.run(run(args))


if __name__ == "__main__":
    main()
