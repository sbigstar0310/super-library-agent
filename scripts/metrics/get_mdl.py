# ----------------------------------------------------------------------
# Entry / cache
# ----------------------------------------------------------------------

@dataclass
class Entry:
    """One scoreable item (paper / task / webgen app)."""
    label: str
    app_dir: str
    lib_dir: str | None
    save_dir: str | None


@dataclass
class ResolveResult:
    """Returned by each per-task resolver."""
    entries: list[Entry]
    eval_root: str | None = None  # directory for the aggregate summary
    header_lines: list[str] = field(default_factory=list)


class LibNllCache:
    """Caches lib NLL per lib_dir within one CLI run.

    Replaces the pre-refactor pattern of stuffing ``_precomputed_lib`` into
    entry dicts. ``get(lib_dir)`` returns ``(library_nll, library_tokens)``
    suitable for ``MDLMetric.ascore(precomputed_lib=...)``.
    """

    def __init__(self, metric: MDLMetric, task: TaskConfig, *, strip_comments: bool):
        self._metric = metric
        self._task = task
        self._strip_comments = strip_comments
        self._cache: dict[str, tuple[float, int]] = {}

    async def get(self, lib_dir: str | None) -> tuple[float, int] | None:
        if not lib_dir:
            return None
        if lib_dir not in self._cache:
            parser = self._task.parser_module
            strip_fn = parser.strip_comments if self._strip_comments else None
            self._cache[lib_dir] = await self._metric._score_library(
                lib_dir, self._task, strip_fn,
            )
            nll, toks = self._cache[lib_dir]
            print(
                f"Library NLL: {nll:.1f} ({toks} tokens) "
                f"[{lib_dir}]"
                f"{' [comments stripped]' if self._strip_comments else ''}"
            )
        return self._cache[lib_dir]


# ----------------------------------------------------------------------
# Resolvers (one per task family) — pure path logic, no I/O on apps
# ----------------------------------------------------------------------

def _require(cond: bool, msg: str) -> None:
    if not cond:
        raise SystemExit(msg)


def _split_ids(value: str | None) -> list[str] | None:
    return [s.strip() for s in value.split(",") if s.strip()] if value else None


def resolve_unified(args: argparse.Namespace, *, bench: str) -> ResolveResult:
    """Unified backup layout (paperbench / webgen with backup-tag).

    Layout: ``backups/<bench>/<tag>/final/round_<N>/<phase>/tasks/<id>/``
    with ``submission/`` (always) + ``lib/`` (coding|apply) or
    phase-level ``round_<N>/extract/lib/`` (extract).
    """
    _require(bool(args.backup_tag), f"--task {bench} requires --backup-tag.")
    _require(not args.app_root_dir,
             f"--task {bench} cannot be combined with --app_root_dir.")
    _require(bool(args.phase),
             f"--task {bench} requires --phase <baseline|coding|apply|extract>.")
    _require(args.phase in ("baseline", "coding", "apply", "extract"),
             f"--phase must be one of baseline|coding|apply|extract (got {args.phase!r}).")

    round_n = args.round
    if round_n is None:
        round_n = latest_round_in_backup(PROJECT_DIR, bench, args.backup_tag, args.phase)
        _require(round_n is not None,
                 f"No round_N/{args.phase} found under "
                 f"backups/{bench}/{args.backup_tag}/final/. Pass --round explicitly.")

    final_phase = backup_final_phase_dir(PROJECT_DIR, bench, args.backup_tag, round_n, args.phase)
    eval_phase = backup_eval_phase_dir(PROJECT_DIR, bench, args.backup_tag, round_n, args.phase)
    tasks_dir = os.path.join(final_phase, "tasks")
    _require(os.path.isdir(tasks_dir), f"tasks/ not found under {final_phase}")

    tids = _split_ids(args.task_ids)
    if tids is None:
        tids = sorted(d for d in os.listdir(tasks_dir)
                      if os.path.isdir(os.path.join(tasks_dir, d)))

    # Phase-level lib (extract only)
    extract_lib = None
    if args.phase == "extract" and args.lib_dir is None:
        extract_lib = extract_lib_dir_in_backup(PROJECT_DIR, bench, args.backup_tag, round_n)
        if not os.path.isdir(extract_lib):
            print(f"[warn] extract phase lib not found at {extract_lib}; "
                  "scoring without library context.")
            extract_lib = None

    entries: list[Entry] = []
    for tid in tids:
        tdir = task_dir_in_backup(PROJECT_DIR, bench, args.backup_tag, round_n, args.phase, tid)
        submission = os.path.join(tdir, "submission")
        if not os.path.isdir(submission):
            print(f"[skip] {tid}: no submission dir at {submission}")
            continue
        lib_dir = args.lib_dir
        if lib_dir is None:
            if args.phase in ("coding", "apply"):
                per_task_lib = os.path.join(tdir, "lib")
                if os.path.isdir(per_task_lib):
                    lib_dir = per_task_lib
            elif args.phase == "extract":
                lib_dir = extract_lib
        entries.append(Entry(
            label=tid,
            app_dir=submission,
            lib_dir=lib_dir,
            save_dir=os.path.join(eval_phase, "tasks", tid),
        ))

    header = [
        f"[Config] bench={bench} tag={args.backup_tag} round={round_n} phase={args.phase}",
        f"[Config] final_phase={final_phase}",
        f"[Config] eval_phase={eval_phase}",
    ]
    return ResolveResult(entries, eval_phase, header)


def resolve_webgen_legacy(args: argparse.Namespace, task: TaskConfig) -> ResolveResult:
    """Webgen with explicit --app_root_dir (legacy path, one combined output)."""
    _require(bool(args.app_root_dir),
             "--task webgen requires either --app_root_dir or --backup-tag.")

    app_ids = set(_split_ids(args.app_ids) or [])
    entries: list[Entry] = []
    for app in sorted(os.listdir(args.app_root_dir)):
        app_dir = os.path.join(args.app_root_dir, app)
        if not is_valid_codebase(app_dir, task=task):
            continue
        if app_ids and app not in app_ids:
            continue
        entries.append(Entry(
            label=app,
            app_dir=app_dir,
            lib_dir=args.lib_dir,
            save_dir=None,  # webgen-legacy aggregates everything to one file
        ))
    return ResolveResult(entries, eval_root=None)


def resolve(args: argparse.Namespace, task: TaskConfig) -> ResolveResult:
    """Dispatch to the right resolver for the requested task."""
    if args.task == "webgen":
        if args.backup_tag:
            return resolve_unified(args, bench=args.bench or "webgen")
        return resolve_webgen_legacy(args, task)
    # paperbench: `resolve_unified` keys off args.task_ids — translate from
    # --paper-ids so paperbench-flavored invocations still work.
    if args.paper_ids and not args.task_ids:
        args.task_ids = args.paper_ids
    return resolve_unified(args, bench=args.bench or "paperbench")


