"""CLI for MDL/NLL scoring.

Computes MDL for code generated by the SLA agents and writes
``mdl_results.json`` (per app/task) + ``mdl_summary.json`` (aggregate)
under each backup's ``eval_results/`` tree.

Three scoring methods:

- ``dep_aware`` (default): MDL = NLL(lib) + Σ NLL(file | direct_deps).
  See ``el-agent/src/utils/mdl/scoring.py``.
- ``concat`` (legacy): MDL = NLL(lib) + Σ NLL(file | full_lib_prefix).
  See ``el-agent/src/utils/mdl/concat.py``.
- ``shared_concat``: MDL = NLL(cat(lib)) + Σ_app NLL(cat(app) | cat(lib)).
  Lib counted once across all apps in a suite. App-internal files see each
  other (sibling driver compression). See
  ``el-agent/src/utils/mdl/shared_concat.py``.

Two task modes (``--task``), each with its own backup layout:

- ``webgen``     React/JS, optional ui-lib. Legacy "loose" or unified layout.
- ``paperbench`` Python, unified layout:
                 ``backups/<bench>/<tag>/final/round_<N>/<phase>/tasks/<tid>/``.

Examples
--------

::

    # Webgen, explicit dirs
    python scripts/metrics/get_mdl.py \\
        --app_root_dir backups/poc-oracle-ver7-t1/final/apps \\
        --lib_dir       backups/poc-oracle-ver7-t1/final/ui-lib

    # Webgen, unified backup tag
    python scripts/metrics/get_mdl.py --task webgen \\
        --backup-tag sla-ours-v3-t1 --phase apply --round 4

    # Paperbench (unified layout — --phase required, --round defaults to latest)
    python scripts/metrics/get_mdl.py --task paperbench \\
        --backup-tag pb-rl-baseline-t1 --phase baseline --round 1 \\
        --paper-ids fre,rice

    # Legacy concat method
    python scripts/metrics/get_mdl.py --task webgen --method concat \\
        --backup-tag sla-ours-v3-t1 --phase apply --round 4

See ``el-agent/src/utils/mdl/README.md`` for the formula and JSON schema.
"""

